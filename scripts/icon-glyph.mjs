// The app glyph (an octopus in order: faint head, four strong arms ending on
// one line, the outer two curled) and every icon drawn from it. Light: paper
// white tile, ink black octopus; dark (where the platform has a dark icon):
// the other way round. Single source for scripts/icons.mjs and the icon
// guard test.

const TILE_HSL = [24, 12, 9];
const MARK_HSL = [36, 30, 97];
const css = ([h, s, l]) => `hsl(${h} ${s}% ${l}%)`;
export const TILE = css(TILE_HSL);
export const MARK = css(MARK_HSL);

/** sRGB 0..1 of an HSL color, for formats without CSS colors. */
function rgb([h, s, l]) {
  const c = (1 - Math.abs((2 * l) / 100 - 1)) * (s / 100);
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l / 100 - c / 2;
  const [r, g, b] = h < 60 ? [c, x, 0] : h < 120 ? [x, c, 0] : [0, c, x];
  return [r + m, g + m, b + m];
}
const hex = hsl => "#" + rgb(hsl).map(v => Math.round(v * 255).toString(16).padStart(2, "0")).join("");
export const TILE_HEX = hex(TILE_HSL);
export const MARK_HEX = hex(MARK_HSL);
export const TILE_RGB = rgb(TILE_HSL);
export const MARK_RGB = rgb(MARK_HSL);

/** In a 32-unit box, centred on (16,16). */
export const WIDTH = 2.5;
const HEAD_C = [16, 15.5];
const HEAD_R = 7;
export const HEAD = "M9 15.5a7 7 0 0 1 14 0";
export const ARMS = "M9 15.5v5.5a2.5 2.5 0 0 1 -2.5 2.5M13.67 15.5v8M18.33 15.5v8M23 15.5v5.5a2.5 2.5 0 0 0 2.5 2.5";
/** The glyph's width (curl tip to curl tip, strokes included): what the icon fractions size. */
const EXTENT = 21.5;
/** Head opacity in color; in alpha-only icons (themed, tray) a bit stronger. */
export const HEAD_OPACITY = 0.45;
const HEAD_ALPHA = 0.5;

const stroke = (d, color, opacity = 1) =>
  `<path d="${d}" fill="none" stroke="${color}"${opacity < 1 ? ` stroke-opacity="${opacity}"` : ""} stroke-width="${WIDTH}" stroke-linecap="round" stroke-linejoin="round"/>`;
const glyph = (color, headOpacity) => stroke(HEAD, color, headOpacity) + stroke(ARMS, color);

/** viewBox centred on the glyph, so its width spans `fraction` of the icon. */
function boxFor(fraction) {
  const size = EXTENT / fraction;
  const o = 16 - size / 2;
  return `${o.toFixed(3)} ${o.toFixed(3)} ${size.toFixed(3)} ${size.toFixed(3)}`;
}

const svg = (viewBox, body, extra = "") =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${viewBox}"${extra}>\n  ${body}\n</svg>\n`;

/** Browser tab and the PWA's base: the rounded tile, ink on paper; paper on ink in dark mode. */
export const favicon = () =>
  svg(
    "0 0 32 32",
    `<style>@media (prefers-color-scheme: dark) { .tile { fill: ${TILE} } .mark { stroke: ${MARK} } }</style>\n  ` +
      `<rect class="tile" width="32" height="32" rx="8" fill="${MARK}"/>\n  ` +
      glyph(TILE, HEAD_OPACITY).replaceAll("<path ", '<path class="mark" ')
  );

/** The mark on its tile for pages (README): `dark` puts paper on ink. */
export const logo = (dark = false) =>
  svg(
    "0 0 32 32",
    // On a white page the paper tile needs its edge: a hairline of ink.
    `<rect x="0.25" y="0.25" width="31.5" height="31.5" rx="7.75" fill="${dark ? TILE : MARK}"${dark ? "" : ` stroke="${TILE}" stroke-opacity="0.08" stroke-width="0.5"`}/>\n  ${glyph(dark ? MARK : TILE, HEAD_OPACITY)}`,
    ' width="64" height="64"'
  );

/** macOS (pre-26) app icon: the tile on Apple's grid (824 of 1024, centred). */
export const macSource = () =>
  `<!-- Generated by scripts/icons.mjs: the favicon on the macOS grid. -->\n` +
  svg(
    "0 0 1024 1024",
    `<svg x="100" y="100" width="824" height="824" viewBox="0 0 32 32">\n    <rect width="32" height="32" rx="7.2" fill="${MARK}"/>\n    ${glyph(TILE, HEAD_OPACITY)}\n  </svg>`,
    ' width="1024" height="1024"'
  );

/** A full-bleed tile (maskable PWA, Apple touch, Android legacy): the OS rounds it. */
export const tile = fraction =>
  svg(boxFor(fraction), `<rect x="-100" y="-100" width="232" height="232" fill="${MARK}"/>\n  ${glyph(TILE, HEAD_OPACITY)}`);

/** Android adaptive foreground: glyph only, inside the 66/108 safe zone. */
export const androidForeground = () => svg(boxFor(0.4), glyph(TILE, HEAD_OPACITY));

/** Alpha-only glyph (Android themed icon, PWA "monochrome"): the OS tints it. */
export const monochrome = fraction => svg(boxFor(fraction), glyph("#000", HEAD_ALPHA));

/** macOS menu bar template: the same glyph filling the box, black on transparent. */
export const tray = () =>
  `<!-- Menu bar (template) icon, generated by scripts/icons.mjs: macOS tints it. -->\n` +
  svg(boxFor(0.9), glyph("#000", HEAD_ALPHA), ' width="44" height="44"');

// Icon Composer fills shapes and ignores strokes: head and arms as outlines.
const h = WIDTH / 2;
const disc = ([x, y]) => `<circle fill="#000" cx="${x}" cy="${y}" r="${h}"/>`;
const n = v => +v.toFixed(3);

function filledHead() {
  const [cx, cy] = HEAD_C;
  const [o, i] = [HEAD_R + h, HEAD_R - h];
  const band = `<path fill="#000" d="M${n(cx - o)} ${cy}A${o} ${o} 0 0 1 ${n(cx + o)} ${cy}L${n(cx + i)} ${cy}A${i} ${i} 0 0 0 ${n(cx - i)} ${cy}Z"/>`;
  return band + disc([cx - HEAD_R, cy]) + disc([cx + HEAD_R, cy]);
}

function filledArms() {
  const top = 15.5;
  const straight = [
    [9, 21],
    [13.67, 23.5],
    [18.33, 23.5],
    [23, 21],
  ].map(([x, bottom]) => `<rect fill="#000" x="${n(x - h)}" y="${top}" width="${WIDTH}" height="${bottom - top}"/>` + disc([x, top]) + disc([x, bottom]));
  // Curls: a quarter band around (6.5,21) and (25.5,21), radius 2.5.
  const [r, o, i] = [2.5, 2.5 + h, 2.5 - h];
  const left = `<path fill="#000" d="M${6.5 + o} 21A${o} ${o} 0 0 1 6.5 ${21 + o}L6.5 ${21 + i}A${i} ${i} 0 0 0 ${6.5 + i} 21Z"/>`;
  const right = `<path fill="#000" d="M${25.5 - o} 21A${o} ${o} 0 0 0 25.5 ${21 + o}L25.5 ${21 + i}A${i} ${i} 0 0 1 ${25.5 - i} 21Z"/>`;
  return straight.join("") + left + right + disc([6.5, 21 + r]) + disc([25.5, 21 + r]);
}

/** Icon Composer layers (macOS 26): head and arms apart, on the 1024 canvas. */
export const composerLayer = part =>
  svg(boxFor(0.62), part === "head" ? filledHead() : filledArms(), ' width="1024" height="1024"');
