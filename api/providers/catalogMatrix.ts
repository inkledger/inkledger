// The capability matrix of CATALOG.md, written from the catalogue itself so
// the document can't drift from the code (catalogMatrix.test.ts checks it;
// `pnpm catalog:matrix` rewrites it).
import type { EntryCapabilities, TrackerCapabilities } from "@contracts/providers";
import { SINKS, TRACKERS } from "./catalog";
import { SINK_REGISTRY, TRACKER_REGISTRY } from "./registry";

export const MATRIX_START = "<!-- matrix:start (generated by pnpm catalog:matrix, do not edit) -->";
export const MATRIX_END = "<!-- matrix:end -->";

function feedCell(f: EntryCapabilities["feed"]): string {
  if (f.kind === "incremental") return `incremental${f.removals ? " with removals" : ""}`;
  if (f.kind === "window") return f.by === "entryDate" ? `window by entry date ${f.days}d` : `window by change ${Math.round(f.lookbackMs / 86_400_000)}d`;
  return "none";
}

function entriesCell(e: EntryCapabilities): string {
  const reconcile = e.reconcile.kind === "period" ? `reconcile by period${e.reconcile.maxDays ? ` (${e.reconcile.maxDays}d)` : ""}` : "no reconcile";
  const tail = `feed ${feedCell(e.feed)}; ${reconcile}`;
  if (e.model === "dayTotals") return `day totals, ${e.write.set ? "set" : "read only"}; ${tail}`;
  const write = e.write.mode === "none" ? "read only" : `update ${e.write.update}${e.write.delete ? ", delete" : ""}`;
  return `${e.shape}, ${write}; ${tail}`;
}

function timeCell(c: TrackerCapabilities): string {
  const t = c.time;
  if (t.mode === "entries") return entriesCell(t.entries);
  if (t.mode === "counter") return `counter${t.concurrency === "revision" ? " (revision)" : ""}`;
  return t.remoteTotals ? "local (service totals)" : "local";
}

function goneCell(c: TrackerCapabilities): string {
  const g = c.sync.gone;
  const reasons = [g.deleted && "deleted", g.lostAccess && "lostAccess", g.movedOut && "movedOut", g.transfer === "withSuccessor" && "transferred"].filter(Boolean);
  return reasons.length ? reasons.join(", ") : "none reported";
}

function hooksCell(c: TrackerCapabilities): string {
  if (!c.sync.webhooks) return "none";
  // Grouped by payload mode, each mode named: "full: a, b; signal: c".
  return (["full", "signal"] as const)
    .map((mode) => [mode, c.sync.webhooks!.filter((w) => w.payload === mode).map((w) => w.event)] as const)
    .filter(([, events]) => events.length > 0)
    .map(([mode, events]) => `${mode}: ${events.join(", ")}`)
    .join("; ");
}

export function catalogMatrix(): string {
  const rows = [
    "| Provider | Adapter status | Workflow sources | Transitions | Search | Comments | Time | Containers | Manage | Gone reported | Webhooks |",
    "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const [type, { capabilities: c }] of Object.entries(TRACKERS)) {
    const sources = c.workflow.sources.map((s) => `${s.kind} (${s.transitions})`).join(", ");
    const tr = c.transitions.write ? "read, apply" : c.transitions.read ? "read" : "none";
    const search = [c.searchText && "text", c.query].filter(Boolean).join(", ") || "none";
    const comments = c.comments.mode === "none" ? "none" : `${c.comments.mode} (${c.comments.formats.join(", ")})`;
    const manage = (["assign", "labels", "create", "edit", "types"] as const).filter((k) => c.manage[k]).join(", ") || "none";
    rows.push(`| ${type} | ${TRACKER_REGISTRY[type as keyof typeof TRACKER_REGISTRY].status} | ${sources} | ${tr} | ${search} | ${comments} | ${timeCell(c)} | ${c.containers ? "listed" : "from issues"} | ${manage} | ${goneCell(c)} | ${hooksCell(c)} |`);
  }
  rows.push("", "| Time sink | Adapter status | Entries | References (in order of preference) | Target | Typical budget |", "| --- | --- | --- | --- | --- | --- |");
  for (const [type, { capabilities: c }] of Object.entries(SINKS)) {
    const target = c.target.use === "none" ? "none" : `${c.target.use} (${c.target.lookup})`;
    const budget = c.typicalRateLimit ? [c.typicalRateLimit.perHour && `${c.typicalRateLimit.perHour}/h`, c.typicalRateLimit.perSecond && `${c.typicalRateLimit.perSecond}/s`].filter(Boolean).join(", ") : "—";
    rows.push(`| ${type} | ${SINK_REGISTRY[type as keyof typeof SINK_REGISTRY].status} | ${entriesCell(c.entries)} | ${c.references.join(", ")} | ${target} | ${budget} |`);
  }
  return rows.join("\n");
}

/** CATALOG.md with its matrix section rewritten. */
export function withMatrix(doc: string): string {
  const a = doc.indexOf(MATRIX_START);
  const b = doc.indexOf(MATRIX_END);
  if (a < 0 || b < a) throw new Error("CATALOG.md has no matrix markers");
  return `${doc.slice(0, a + MATRIX_START.length)}\n${catalogMatrix()}\n${doc.slice(b)}`;
}
